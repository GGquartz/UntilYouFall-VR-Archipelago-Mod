import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOGS = ROOT / "src/apworld/until_you_fall"
HEADER = "// Generated by game data export\n"


def load(name):
    return json.loads((CATALOGS / name).read_text(encoding="utf-8"))


def render_type(declaration, body, namespace="UntilYouFallArchipelago"):
    return f"""{HEADER}
namespace {namespace};

{declaration}
{{
{body}
}}
"""


def game_identity_constants():
    name = json.dumps(load("archipelago.json")["game"])
    return render_type(
        "internal static class GameIdentity", f"    public const string Name = {name};", namespace="UntilYouFall.Shared"
    )


def item_constants():
    definitions = load("items.json")
    constants = []
    bonus_copies = []
    aether_bundles = []

    for item in definitions["Items"]:
        key = item["Key"]
        constants.append(f"    public const long {key}Id = {item['Id']};")
        constants.append(f"    public const string {key}Name = {json.dumps(item['Name'])};")
        if "Copies" in item:
            constants.append(f"    public const int {key}MaxCount = {item['Copies']};")
        if "Amount" in item:
            constants.append(f"    public const int {key}Amount = {item['Amount']};")
        if item.get("Group") == "PlayerBonus":
            bonus_copies.append(f"        [{key}Id] = {key}MaxCount,")
        if item.get("Group") == "AetherBundle":
            aether_bundles.append(f"        [{key}Id] = {key}Amount,")

    for key in ("DamageItemCopies", "StartingTraitCopies"):
        constants.append(f"    public const int {key} = {definitions[key]};")

    constants = "\n".join(constants)
    bonus_copies = "\n".join(bonus_copies)
    aether_bundles = "\n".join(aether_bundles)
    body = f"""{constants}

    public static readonly IReadOnlyDictionary<long, int> PlayerBonusCopies = new Dictionary<long, int>
    {{
{bonus_copies}
    }};

    public static readonly IReadOnlyDictionary<long, int> AetherBundles = new Dictionary<long, int>
    {{
{aether_bundles}
    }};"""
    return render_type("internal static partial class ApItems", body)


def location_constants():
    members = []
    for key, value in load("locations.json").items():
        if isinstance(value, int):
            members.append(f"    public const int {key} = {value};")
        elif isinstance(value, list):
            values = ", ".join(map(str, value))
            members.append(f"    public static readonly int[] {key} = {{ {values} }};")
        elif key == "StageBossSuffixes":
            entries = "\n".join(f"        [{stage}] = {json.dumps(suffix)}," for stage, suffix in value.items())
            members.append(f"""    public static readonly IReadOnlyDictionary<int, string> StageBossSuffixes = new Dictionary<int, string>
    {{
{entries}
    }};""")
        else:
            raise ValueError(f"Unsupported location definition: {key}")
    return render_type("internal static class LocationDefinitions", "\n".join(members))


def difficulty_constants():
    difficulties = load("difficulties.json")
    first_id = difficulties[0]["Id"]
    actual_ids = [difficulty["Id"] for difficulty in difficulties]
    expected_ids = list(range(first_id, first_id + len(difficulties)))
    if actual_ids != expected_ids:
        raise ValueError("Difficulty item IDs error")
    names = ", ".join(json.dumps(difficulty["Name"]) for difficulty in difficulties)
    body = f"""    public const long FirstItemId = {first_id};
    public static readonly string[] Names = {{ {names} }};"""
    return render_type("internal sealed partial record DifficultySettings", body)


def option_range_constants():
    constants = []
    for option_name, limits in load("option_ranges.json").items():
        for limit_name, value in limits.items():
            constants.append(f"    public const int {option_name}{limit_name} = {value};")
    return render_type("internal static class OptionRanges", "\n".join(constants))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated constants are stale")
    args = parser.parse_args()
    outputs = {
        ROOT / "src/shared/GameIdentity.Generated.cs": game_identity_constants(),
        ROOT / "src/mod/Archipelago/ApItems.Generated.cs": item_constants(),
        ROOT / "src/mod/Checks/LocationDefinitions.Generated.cs": location_constants(),
        ROOT / "src/mod/Difficulty/DifficultySettings.Generated.cs": difficulty_constants(),
        ROOT / "src/mod/Archipelago/OptionRanges.Generated.cs": option_range_constants(),
    }
    stale = []
    for path, text in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text, encoding="utf-8")
    if stale:
        raise SystemExit("Stale catalog exports:\n" + "\n".join(stale))
    print("Catalog definitions are current" if args.check else "Exported catalog definitions")


if __name__ == "__main__":
    main()
